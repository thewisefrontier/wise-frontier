"""
scripts/one_off/migrate_supabase_to_aiven.py
---------------------------------------------
2026-10-20 Supabase 무료 플랜 이그레스 초과로 공개 REST(PostgREST)가 402로 막혀 사이트·파이프라인이
전부 멈췄다(사용자 결정: "마이그레이션 마저 진행해서 supabase에서 빠져나오자"). 공개 REST만 막혔고
DB 직접 접속(풀러)은 살아 있어서, 그 경로로 Supabase 최종 상태를 Aiven에 통째로 옮긴다.

순서(재실행해도 같은 결과 — 멱등):
  1) Aiven 쪽 트리거 제거(복사 중 noindex 재계산·리비전 기록이 원본 값을 바꾸지 않게)
  2) 스키마 구조(테이블·누락 컬럼) — Supabase 카탈로그에서 실행 시점에 생성(손으로 옮겨 적지 않음)
  3) 대상 테이블 전부 TRUNCATE 후 id 구간별 COPY(Aiven 무료 플랜은 한 번에 큰 COPY를 하면
     연결이 끊긴 전례가 있음 — docs/DB_STANDBY.md)
  4) 제약조건·인덱스 → 함수·트리거(Supabase Auth 전용 is_admin/is_staff 제외) → 시퀀스 재설정
  5) 테이블별 건수 대조(로그엔 건수만 — 공개 저장소라 데이터·접속정보는 찍지 않는다)

raw_candidates는 클러스터링 창(96시간)만, full_text 없이 옮긴다(필요하면 db.hydrate_full_text가
다시 채움 — Aiven 무료 1GB 보호).

실행: one_off_task.yml(script=one_off/migrate_supabase_to_aiven.py)
필요 env: AIVEN_SERVICE_URI, SUPABASE_DB_PASSWORD
"""

import io
import os
import sys

import psycopg2

PROJECT_REF = "fotdngseksqaghvtcvqh"
POOLER_HOSTS = ["aws-1-ap-northeast-2.pooler.supabase.com", "aws-0-ap-northeast-2.pooler.supabase.com"]
CHUNK = {"articles": 1500, "raw_candidates": 5000, "view_snapshots": 50000, "article_revisions": 1000}
DEFAULT_CHUNK = 20000
SKIP_TABLES = {"rss_raw_queue"}  # 원본 0건
EXCLUDE_FUNCS = ("is_admin", "is_staff")  # auth.uid() 의존

# 부모 먼저(FK). 나머지는 카탈로그 순서대로 뒤에 붙는다.
ORDER_FIRST = ["articles"]


def connect_src():
    pw = os.environ["SUPABASE_DB_PASSWORD"]
    last = None
    for host in POOLER_HOSTS:
        try:
            conn = psycopg2.connect(host=host, port=5432, dbname="postgres", user=f"postgres.{PROJECT_REF}",
                                    password=pw, sslmode="require", connect_timeout=15)
            print(f"[src] Supabase 풀러 접속 성공: {host}")
            return conn
        except Exception as e:  # 다음 후보로
            last = e
            print(f"[src] {host} 실패: {type(e).__name__}")
    raise SystemExit(f"Supabase 직접 접속 실패: {type(last).__name__}")


def connect_dst():
    conn = psycopg2.connect(os.environ["AIVEN_SERVICE_URI"], connect_timeout=15)
    print("[dst] Aiven 접속 성공")
    return conn


def one(cur, sql, args=None):
    cur.execute(sql, args)
    return cur.fetchone()[0]


STRUCTURE_SQL = r"""
with tbls as (
  select k.oid, k.relname from pg_class k join pg_namespace n on n.oid=k.relnamespace
  where n.nspname='public' and k.relkind in ('r','p')
),
coldef as (
  select t.relname, a.attnum, a.attname,
    format_type(a.atttypid, a.atttypmod)
    || case when a.attidentity in ('a','d') then ' GENERATED BY DEFAULT AS IDENTITY'
            when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) else '' end as typedef,
    a.attnotnull nn
  from tbls t join pg_attribute a on a.attrelid=t.oid and a.attnum>0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid=t.oid and d.adnum=a.attnum
),
seqs as (
  select distinct (regexp_match(pg_get_expr(d.adbin,d.adrelid), $$nextval\('([^']+)'$$))[1] s
  from pg_attrdef d join tbls t on t.oid=d.adrelid where pg_get_expr(d.adbin,d.adrelid) like 'nextval%%'
)
select string_agg(line, E'\n' order by ord, line) from (
  select 1 ord, 'CREATE SEQUENCE IF NOT EXISTS ' || s || ';' line from seqs
  union all
  select 2, 'CREATE TABLE IF NOT EXISTS public.' || relname || ' (' || E'\n  '
    || string_agg(attname || ' ' || typedef || case when nn then ' NOT NULL' else '' end, E',\n  ' order by attnum) || E'\n);'
  from coldef group by relname
  union all
  select 3, 'ALTER TABLE public.' || relname || ' ADD COLUMN IF NOT EXISTS ' || attname || ' '
    || regexp_replace(typedef, ' GENERATED BY DEFAULT AS IDENTITY', '') || ';'
  from coldef
) x
"""

CONSTRAINT_INDEX_SQL = r"""
select string_agg(line, E'\n' order by ord, sub, line) from (
  select 4 ord, case contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end sub,
    'DO $do$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname=' || quote_literal(conname)
    || ') THEN ALTER TABLE public.' || conrelid::regclass::text || ' ADD CONSTRAINT ' || conname || ' '
    || pg_get_constraintdef(oid) || '; END IF; END $do$;' line
  from pg_constraint
  where connamespace='public'::regnamespace and contype in ('p','u','f','c')
    and pg_get_constraintdef(oid) not like '%%auth.users%%'
  union all
  select 5, 0, regexp_replace(indexdef, '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';'
  from pg_indexes
  where schemaname='public' and indexname not in (select conname from pg_constraint where connamespace='public'::regnamespace)
) x
"""

FUNC_SQL = r"""
select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname)
from pg_proc p join pg_namespace n on n.oid=p.pronamespace
where n.nspname='public' and p.prokind in ('f','p')
  and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')
  and p.proname <> all (%s)
"""

TRIGGER_SQL = r"""
select tg.tgname, c.relname, pg_get_triggerdef(tg.oid)
from pg_trigger tg join pg_class c on c.oid=tg.tgrelid join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and not tg.tgisinternal
"""


def table_list(scur):
    scur.execute("""select k.relname from pg_class k join pg_namespace n on n.oid=k.relnamespace
                    where n.nspname='public' and k.relkind in ('r','p') order by k.relname""")
    names = [r[0] for r in scur.fetchall() if r[0] not in SKIP_TABLES]
    return ORDER_FIRST + [t for t in names if t not in ORDER_FIRST]


def columns(scur, table):
    scur.execute("""select column_name from information_schema.columns
                    where table_schema='public' and table_name=%s order by ordinal_position""", (table,))
    return [r[0] for r in scur.fetchall()]


def has_id(scur, table):
    scur.execute("""select data_type from information_schema.columns
                    where table_schema='public' and table_name=%s and column_name='id'""", (table,))
    r = scur.fetchone()
    return bool(r) and r[0] in ("integer", "bigint")


def source_filter(table):
    if table == "raw_candidates":
        return ("created_at >= to_char(now() at time zone 'Asia/Seoul' - interval '96 hours', "
                "'YYYY-MM-DD HH24:MI')")
    return "true"


def copy_table(src, dst, table):
    scur, dcur = src.cursor(), dst.cursor()
    cols = columns(scur, table)
    sel_cols = ["NULL::text AS full_text" if (table == "raw_candidates" and c == "full_text") else f'"{c}"'
                for c in cols]
    col_list = ", ".join(f'"{c}"' for c in cols)
    where = source_filter(table)
    total = 0
    if has_id(scur, table):
        lo, hi = scur.execute(f"select min(id), max(id) from public.{table} where {where}") or scur.fetchone()
        if lo is None:
            print(f"  {table}: 원본 0건")
            return 0
        step = CHUNK.get(table, DEFAULT_CHUNK)
        start = lo
        while start <= hi:
            end = start + step
            buf = io.StringIO()
            scur.copy_expert(f"COPY (SELECT {', '.join(sel_cols)} FROM public.{table} "
                             f"WHERE {where} AND id >= {start} AND id < {end} ORDER BY id) TO STDOUT", buf)
            n = buf.getvalue().count("\n")
            if n:
                buf.seek(0)
                dcur.copy_expert(f"COPY public.{table} ({col_list}) FROM STDIN", buf)
                dst.commit()
                total += n
            start = end
    else:
        buf = io.StringIO()
        scur.copy_expert(f"COPY (SELECT {', '.join(sel_cols)} FROM public.{table} WHERE {where}) TO STDOUT", buf)
        total = buf.getvalue().count("\n")
        if total:
            buf.seek(0)
            dcur.copy_expert(f"COPY public.{table} ({col_list}) FROM STDIN", buf)
            dst.commit()
    print(f"  {table}: {total}건 복사")
    return total


def main():
    src = connect_src()
    src.set_session(readonly=True)
    dst = connect_dst()
    scur, dcur = src.cursor(), dst.cursor()

    print("[1] Aiven 확장·트리거 정리")
    dcur.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm; CREATE EXTENSION IF NOT EXISTS pgcrypto;")
    dcur.execute("""select tg.tgname, c.relname from pg_trigger tg join pg_class c on c.oid=tg.tgrelid
                    join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and not tg.tgisinternal""")
    for tg, rel in dcur.fetchall():
        dcur.execute(f'DROP TRIGGER IF EXISTS "{tg}" ON public."{rel}"')
    dst.commit()

    print("[2] 스키마 구조 동기화")
    dcur.execute(one(scur, STRUCTURE_SQL))
    # 기존 Aiven 테이블의 GENERATED ALWAYS identity는 COPY로 원본 id를 못 넣는다 → BY DEFAULT로
    dcur.execute("""do $$ declare r record; begin
      for r in select table_name, column_name from information_schema.columns
               where table_schema='public' and is_identity='YES' and identity_generation='ALWAYS' loop
        execute format('alter table public.%I alter column %I set generated by default', r.table_name, r.column_name);
      end loop; end $$;""")
    dst.commit()

    tables = table_list(scur)
    print(f"[3] 데이터 복사 대상 {len(tables)}개 테이블 — TRUNCATE 후 구간 COPY")
    dcur.execute("TRUNCATE " + ", ".join(f"public.{t}" for t in tables) + " CASCADE")
    dst.commit()
    src_counts = {}
    for t in tables:
        src_counts[t] = copy_table(src, dst, t)

    print("[4] 제약조건·인덱스")
    dcur.execute("SET statement_timeout = 0")
    dcur.execute(one(scur, CONSTRAINT_INDEX_SQL))
    dst.commit()

    print("[5] 함수·트리거")
    dcur.execute(one(scur, FUNC_SQL % ", ".join(f"'{f}'" for f in EXCLUDE_FUNCS)))
    scur.execute(TRIGGER_SQL)
    for tg, rel, ddl in scur.fetchall():
        dcur.execute(f'DROP TRIGGER IF EXISTS "{tg}" ON public."{rel}"')
        dcur.execute(ddl)
    dst.commit()

    print("[6] 시퀀스·identity 재설정")
    # pg_get_serial_sequence는 컬럼 "소유" 시퀀스만 찾는다 — CREATE SEQUENCE + DEFAULT nextval로
    # 만든 시퀀스(aiven_init.sql 방식)는 NULL이라, 기본값 문자열에서 이름을 직접 뽑는다. 이걸
    # 빠뜨리면 시퀀스가 1부터라 새 기사 INSERT가 기존 id와 충돌한다.
    dcur.execute("""do $$ declare r record; s text; m bigint; begin
      for r in select table_name, column_name, column_default from information_schema.columns
               where table_schema='public' and (column_default like 'nextval%' or is_identity='YES') loop
        s := coalesce(pg_get_serial_sequence('public.' || quote_ident(r.table_name), r.column_name),
                      substring(r.column_default from $re$nextval\\('([^']+)'$re$));
        if s is null then continue; end if;
        execute format('select max(%I) from public.%I', r.column_name, r.table_name) into m;
        if m is not null then perform setval(s, m, true); end if;
      end loop; end $$;""")
    dst.commit()

    print("[7] 건수 대조")
    bad = 0
    for t in tables:
        dcur.execute(f"select count(*) from public.{t}")
        d = dcur.fetchone()[0]
        mark = "OK" if d == src_counts[t] else "불일치"
        bad += mark != "OK"
        print(f"  {t}: 원본 {src_counts[t]} / Aiven {d} {mark}")
    dcur.execute("select pg_size_pretty(pg_database_size(current_database()))")
    print(f"  Aiven DB 크기: {dcur.fetchone()[0]}")
    src.close()
    dst.close()
    if bad:
        sys.exit(1)
    print("완료")


if __name__ == "__main__":
    main()
